"""인구 수집 범위 — 역이 있는 시군구만 받으면 그 사이 구간의 인구가 비어 노선 수요가 낮게 나온다."""

import sgis_population as S


def test_전국_시군구를_시도마다_모은다():
    stage = {None: [{'cd': '11'}, {'cd': '33'}],
             '11': [{'cd': '11010'}, {'cd': '11020'}],
             '33': [{'cd': '33020'}]}

    assert S.all_sgg(stage.get) == {'11010', '11020', '33020'}


def test_시군구가_없는_시도는_시도_코드를_그대로_쓴다():
    # 세종은 시군구 단계 응답에 하위가 없을 수 있다 — 빠지면 그 지역이 통째로 빈다
    stage = {None: [{'cd': '29'}], '29': []}

    assert S.all_sgg(stage.get) == {'29'}

-- S7: 편익 산정 원단위
--
-- 출처 국토교통부 「교통시설 투자평가지침」 제7판 (국토교통부 지침 2022-500호, 2022.09.02)
--   시간가치     표 4-44 전국권 철도 1인당 시간가치 (238쪽) 중 **광역도시철도** 등급
--   사회적 할인율 6.2.1 (430쪽)        분석기간·공사기간  6.2.2 (430쪽)
--   2단계 할인식  6.3.1 ② (433쪽)      원단위 갱신 지수   6.2.3 (4) (431쪽)
--
-- 시간가치는 지침이 통행목적 비율로 가중평균한 값이다.
--   광역도시철도 = 업무 0.0414 × 22,775 + 비업무 0.9586 × 5,033 = 5,768원/인·시 (2013년 기준)
--   업무통행 비율이 4%뿐이라 사실상 비업무 5,033원이 값을 지배한다.
--   고속철도(10,197)·일반철도(6,830)와 다른 이유가 이것이다.
-- 지침은 원단위 갱신에 **소비자물가지수**를 쓰라고 정한다 (건설비의 GDP 디플레이터와 다르다).
--   2013→2025 = 135.002/107.684 = 1.2537  →  7,231원/인·시 (2025년 기준)
--   지침이 2013→2020 에 쓴 지수 107.5 가 World Bank 한국 CPI 비와 정확히 일치해
--   같은 통계 계열임을 확인했다 (115.777/107.684 = 1.075).
--
-- 할인·분석기간은 철도사업 기준이다. 일반 교통시설은 30년·4.5% 단일이지만
-- 철도는 분석기간 40년이고 개통 후 31~40년 구간에 3.5%를 적용한다.
--
-- **첨두율은 지침에 원단위가 없다** — 수요분석 결과에서 얻으라고만 한다(지침 전체 확인).
-- 그래서 서울 시간대별 승하차로 직접 측정했다 (`etl/seoul_peak.py`, data/build/station_peak.csv).
--   613개 역 × 3개월(2026-06~08) 합계 기준 첨두는 **18시 9.87%** (8시 9.51%)
--   역별 첨두 비중 중앙값 0.1016, 사분위 0.0924~0.1119 — 노선은 역의 합이므로
--   역별 중앙값이 아니라 **전체 합계 기준**을 쓴다
--   수요 모델의 종속변수가 일 승차+하차이므로 첨두율도 (승차+하차)로 맞췄다
--   **주말이 섞여 있어 평일 설계 첨두보다 낮다.** 수요 모델도 28일 평균(주말 포함)이라
--   둘의 기준은 서로 맞지만, 설계 첨두로 쓰려면 평일만 뽑아야 한다
--
-- **peak_direction_ratio 는 방향 비중이 아니라 환산계수다.** 식이
--   첨두 단면 = 일(승차+하차) × 첨두율 × 이 값
-- 인데 역 승하차 합계는 단면 통행량이 아니다(한 통행을 승차·하차로 두 번 센다).
-- 이 값이 "역 이용량 → 최대 단면 방향 통행량" 변환을 혼자 떠맡는다.
-- 서울교통공사 혼잡도로 실측했다 (`etl/seoul_congestion.py`, data/build/line_congestion.csv).
--   혼잡도는 교통카드 O/D 기반 **재차인원**이라 역 승하차가 아니라 단면 통행량이다
--   pphpd = 혼잡도/100 × 160(1량 정원) × 편성당칸수 × (60 ÷ 출근 시격)
--   K = pphpd 최대 ÷ (노선 일 승하차 × 첨두율)
--
-- 노선별 K: 2호선 0.209 / 5호선 0.311 / 6호선 0.322 / 8호선 0.506
--           (직결 운행인 1호선 0.746 · 4호선 0.518 · 3호선 0.399 · 7호선 0.379 은 제외 —
--            다른 기관 역에서 승차한 승객이 단면에 실리지만 분모에 없어 과대로 나온다)
-- 중앙값 0.3165 를 쓴다. 가정값 0.6 의 절반 정도다.
--
-- 이 계수는 네 가지를 한꺼번에 담고 있다
--   ① 승하차 이중 계산 보정(×0.5) ② 방향 쏠림(실측 중앙값 0.79) ③ 단면 집중
--   ④ **평일 보정** — 혼잡도는 평일, 첨두율·수요 모델은 주말 포함 평균이라
--      K 가 그 차이를 흡수한다. 결과는 평일 설계 첨두로 읽어야 맞다
--
-- 한계: K 가 노선 연장에 반비례한다(r=0.77). 표본이 30~60km 노선 4개뿐이라
-- 10~20km 짧은 노선은 과소 추정된다. 연장 함수로 세우려면 평일 시간대별 승하차
-- (역별 일별 시간대별 자료)로 첨두율을 평일만 분리해야 한다.
--
-- **실측 최대 단면은 20,403(8호선)~57,754(2호선)명/시였다.** 6·8호선은 실제 운영 중인
-- 중전철인데도 `mode_capacity.pphpd_min` 40,000 에 못 미친다 — 하한이 비현실적으로
-- 높다는 뜻이고, "수송능력 대비 과잉 투자" 경고가 쉽게 붙는 진짜 원인이다.
--
-- baseline_speed_kmh 는 전환 전 수단의 속도다. 지침의 편익은 전환 이용자의 수단 전후
-- 통행시간 차이로 산정하므로(표 4-44 ⑩) 단일 기준속도 자체가 근사이지만, 값은
-- 국가지표체계「광역시별 승용차 및 시내버스 평균 통행속도」(통계청 승인통계 제20109호)에서
-- 가져왔다. 2025년 시내버스: 서울 17.1 / 대구 17.5 / 광주 21.0 / 대전 21.6 / 부산 24.4 /
-- 울산 24.8 → 중앙값 21.3 (data/seed/road_speed.csv). 인천은 2022년부터 미공표.
--   · 전국 적용이라 중앙값을 썼다. 서울만 보면 17.1 로 더 느려 편익이 커진다
--   · 승용차 전환을 기준으로 보면 27.2 (7개 시 중앙값)로 편익이 크게 줄어든다
--   · **BRT 저급형(18.0km/h)은 이 기준보다 느려 편익이 항상 0 이다.** 오류가 아니라
--     "시내버스보다 느린 BRT는 시간을 절감하지 못한다"는 결과다. 다만 BRT 저급형
--     속도 자체가 아직 가정값이라 결론을 확정할 수 없다 (S1 주석 참고)
-- 관리자 페이지에서 수정할 수 있어야 한다 (제안서 기능 정의).

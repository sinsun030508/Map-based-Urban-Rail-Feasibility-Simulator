-- 못 미쳤다. 서울 6·8호선이 "지하철을 지을 이유가 없는 노선"으로 판정됐던 셈이다.
--
--   중전철 20,000  실측 — 운영 중인 중전철의 최저 단면(8호선 20,403)
--   경전철  3,000  추정 — 우이신설 2,946 / 신림 2,999 (혼잡도 자료가 1~8호선뿐이라
--                  일 승하차에 첨두율·환산계수를 적용해 환산했다)
--   나머지   NULL  근거가 없거나 경고가 무의미하다
--     · 복선전철·단선전철 — 광역철도 승하차 자료가 구간별로 쪼개져 있어
--       노선 단위 단면을 세울 수 없다 (한산한 경춘선부터 붐비는 경의선까지 폭이 크다)
--     · 트램·BRT — 더 싼 철도 대안이 없어 "과잉 투자" 경고 자체가 의미가 없고,
--       국내 실측 단면 자료도 없다
-- NULL 이면 과잉 투자 경고를 띄우지 않는다. 근거 없이 경고하지 않는다.
--
-- pphpd_max 는 수송능력 상한 그대로다. 실측 최대 단면 57,754명/시(2호선)가
-- 중전철 상한 80,000 안에 들어와 값이 타당한 것을 확인했다.

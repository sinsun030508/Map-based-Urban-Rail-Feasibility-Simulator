-- speed_kmh (표정속도 = 운행거리 ÷ (주행시간 + 정차시간))
--
-- 근거는 `data/seed/rail_speed.csv` — 노선별 출처와 중앙값 포함 여부를 적어 뒀다.
-- 평균이 아니라 **중앙값**을 쓴다 (김포 골드라인 45.08 같은 광역형에 끌려간다).
--
--   중전철   32.4  서울 8 + 인천1 + 부산1·2·3 = 12개 노선 중앙값
--   경전철   29.3  우이신설 28.70 / 부산4 28.80 / 신림 29.25 / 인천2 32.50 / 김포 45.08
--   트램     22.1  대전 2호선 설계값 — **국내 운영 노선이 없어 실측 불가**
--   복선전철 47.6  신분당선 운영사 발표
--   급행     91.8  GTX-A 운정중앙~서울역 90.14 / 수서~동탄 93.43 의 중앙값
--
-- 출처는 서울·부산교통공사 공공데이터(표정속도 직접 공표), 인천교통공사·김포시·대전시·
-- 신분당선(주) 공식 페이지, 서울시 보도자료(연장÷소요시간)다. 소요시간이 있는 노선은
-- 연장÷소요시간이 공표 표정속도와 ±0.05 안에서 맞는 것을 확인했다 (김포 -0.85,
-- 신분당선 +1.86 은 기관이 쓴 거리·시간이 공표 반올림값과 달라서다).
-- 2호선 성수·신정지선은 본선과 중복 집계되므로 제외했다 (역간격과 같은 규칙).
--
-- **BRT 2종은 여전히 가정값이다.** 공식 표정속도를 못 찾았다. 세종 S-BRT 의 35km/h는
-- **급행 기준 목표치**라 전 역 정차를 전제한 우리 표정속도와 비교할 수 없어 쓰지 않았다.
-- BRT 저급형 18.0 은 `baseline_speed_kmh`(시내버스 21.3)보다 느려 편익이 항상 0 이다.
-- 이 0 을 뒤집으려면 BRT 속도부터 실측해야 한다 — 숫자를 맞추려고 올리지 말 것.
--
-- 단선전철 45.0 은 가정값이다. max_length_km 도 같은 성격이며,
-- 관리자 페이지에서 수정할 수 있어야 한다.
--
-- =====================================================
-- 복선전철을 둘로 가른 이유 — 중앙값이 아무도 대표하지 않았다
-- =====================================================
--
-- 전에는 한 행에 `spacing_km 4.30` 과 `speed_kmh 47.6` 이 같이 있었다. 그런데
-- 4.30 은 10개 노선 **전체** 중앙값이고 47.6 은 **신분당선 하나**(그 노선의
-- 역간격은 2.09km)였다. 역은 4.30km 간격으로 놓고 속도는 2.09km 간격 노선의
-- 것을 쓴 셈이다 — 역간격이 두 배 넓으면 정차가 절반이라 더 빨라야 하는데
-- 안 빨라졌다. 역간격·속도 회귀(속도 = 18.56 + 12.65 × 역간격, 노선 18개, R² 0.925)와
-- **−35%** 어긋났다.
--
-- 왜 하필 중앙값이 빗나갔나 — **역간격 분포가 쌍봉이다.**
--
--   1.67  1.98  2.25  2.99  3.62  6.47 │ 4.98  6.18  7.67  7.94
--   └────── 이름에 '급행' 없음 (6개) ──┘ │ └── 이름에 '급행' (4개) ──┘
--              중앙값 2.62              │        중앙값 6.92
--                              ↑ 4.30 = 아무 노선도 없는 틈
--
-- 중앙값은 "가운데 값"이지 "대표값"이 아니다. 봉우리가 둘이면 가운데는 골짜기다.
-- 가르면 복선전철의 어긋남이 −35% → **−8%** 로 줄었다.
--
-- **비용은 가르지 않았다.** km당 사업비만 보면 급행 579 / 일반 1,064 억으로 두 배
-- 갈리지만, 비용 회귀에 이미 `log(역수)` 가 있어 역수를 알고 난 뒤 잔차 차이는
-- 1.02배(t=+0.12)뿐이다. 급행은 "급행이라서" 싼 게 아니라 **역이 적어서** 싸다.
-- 그래서 S5 에서 급행은 복선전철의 비용 계수를 그대로 쓴다.
--
--   **다만 "비용 차이가 없다"고 말하면 과한 주장이다.** 급행 n=4 라 검출 한계가
--   1.50배다 — 그보다 작은 차이는 이 표본에서 보이지 않는다. `log(역수)` 를 아예
--   빼고 돌려도 t가 2를 넘지 않았다. 즉 이 검정은 **어느 쪽도 가리지 못한다.**
--   결론(가르지 않는다)은 표본 4개에 더미를 더 붙이는 것이 과적합이기 때문이다.
--   검사·재현: `cd etl && python mode_speed_check.py`
--
-- **급행 속도는 n=2 이고 기준이 섞여 있다.** 수서~동탄 93.43 은 운행 시간표
-- 기준이고(미디어허브 비교표 21분 + 공식 FAQ 첫차 시각으로 교차검증: 동탄
-- 05:30→성남 05:44 에 수서~성남 7분을 더해 21분), 운정중앙~서울역 90.14 는
-- 발표 시점에 그 구간이 **영업시운전 중**이라 운행 실적이 아니다. 둘이 3.6% 안에서
-- 맞아 기준 차이가 값을 흔들지 않지만, 개통 뒤 공표를 찾으면 교체할 것.
-- 개통 전 계획값 19분(=103.26km/h)은 실제보다 2분 짧았다 — 전에 그 값이 들어 있었다.
